function aplicar(regras: Regra[], t: string): string | null {
  for (const [r, e] of regras) {
    const m = t.match(r);
    if (!m) continue;
    const c = typeof e === "string" ? e : e(m, t);
    if (c) return c;
  }
  return null;
}

export type TipoVinculo = "material" | "mao_de_obra" | "equipamento" | "servico" | "taxa";

/** Taxas, água, energia, frete e transporte não têm forma física no canteiro. */
export function semFormaFisica(descricao: string, tipo: TipoVinculo): boolean {
  return tipo === "taxa" || /^AGUA\b|ENERGIA ELETRICA|^FRETE|TRANSPORTE/.test(normalizar(descricao));
}

/** Modelo 3D de um insumo, pela descrição e pelo tipo. */
export function modeloDoInsumo(descricao: string, tipo: TipoVinculo): string | null {
  const t = normalizar(descricao);
  if (tipo === "mao_de_obra") return aplicar(REGRAS_MAO_DE_OBRA, t);
  if (tipo === "equipamento") return aplicar(REGRAS_EQUIPAMENTO, t) ?? aplicar(REGRAS_MATERIAL, t);
  if (semFormaFisica(descricao, tipo)) return null;
  return aplicar(REGRAS_MATERIAL, t) ?? aplicar(REGRAS_EQUIPAMENTO, t);
}

/** Kit ou serviço montado de uma composição. */
export function modeloDoServico(descricao: string): string | null {
  return aplicar(REGRAS_SERVICO, normalizar(descricao));
}
