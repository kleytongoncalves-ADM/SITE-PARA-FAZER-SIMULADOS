/**
 * Ligação entre os insumos e composições do orçamento e os modelos da biblioteca 3D.
 * O modelo é escolhido pela descrição (regras de texto, como no plano da biblioteca), nunca pelo item:
 * todo orçamento que usar o mesmo insumo mostra o mesmo modelo, em qualquer mês da tabela.
 */

/** Maiúsculas, sem acento, espaços simples. "Bloco cerâmico 9 x 19" vira "BLOCO CERAMICO 9X19". */
export function normalizar(t: string): string {
  return t
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/N[º°o]\s*/g, "N ")
    .replace(/(\d)\s*X\s*(?=\d)/g, "$1X")
    .replace(/[^\w,./%+\-X ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

type Escolha = string | ((m: RegExpMatchArray, t: string) => string | null);
type Regra = [RegExp, Escolha];

/** Diâmetro (mm) citado na descrição: "DN 25 MM", "25MM", "Ø 25". */
function diametro(t: string): number | null {
  const m = t.match(/(?:DN|D=|DIAMETRO|O)\s*=?\s*(\d{2,4})\s*(?:MM)?\b/) ?? t.match(/\b(\d{2,4})\s*MM\b/);
  return m ? Number(m[1]) : null;
}
function maisProximo(valor: number | null, opcoes: [number, string][]): string {
  if (valor == null) return opcoes[0][1];
  return opcoes.reduce((a, b) => (Math.abs(b[0] - valor) < Math.abs(a[0] - valor) ? b : a))[1];
}

/** Bitola do aço na descrição: "10,0 MM", "12,5 MM". */
function bitola(t: string): number | null {
  const m = t.match(/(\d{1,2}(?:,\d)?)\s*MM/);
  return m ? Number(m[1].replace(",", ".")) : null;
}

